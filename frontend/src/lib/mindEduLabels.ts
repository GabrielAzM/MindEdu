export function formatMindEduLabel(value: string): string {
  const normalized = value.trim().toLocaleLowerCase("pt-BR");
  if (labels[normalized]) return labels[normalized];

  return normalized
    .split("_")
    .map((word) => words[word] ?? word)
    .join(" ");
}
